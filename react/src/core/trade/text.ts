/** SKT_RE */
const SKT_RE: [RegExp, string | ((...a: string[]) => string)][] = [
  [/^검증 구간 파생 기록, (현재 전략|전체 전략) 범위$/, '검증 구간 기록, $1 기준'],
  [/^진입 신호를 탐색하는 중입니다\.$/, '진입 신호를 찾고 있습니다.'],
  [/\s*\(시뮬레이션\)/g, ''],
  [/^이전 판단 더 보기 \((\d+)\)$/, '이전 판단 더 보기, $1건'],
  [/^시장가 (매도|매수) 전량, /, '전량 시장가 $1, '],
  [/^(\d{4})\.(\d{2})\.(\d{2})$/, (_m, y, m, d) => y + '. ' + +m + '. ' + +d + '.'],
  [/^(\d{4})\.(\d{2})\.(\d{2}) ~ (\d{4})\.(\d{2})\.(\d{2})$/, (_m, a, b, c, d, e, g) => a + '. ' + +b + '. ' + +c + '. ~ ' + d + '. ' + +e + '. ' + +g + '.'],
];

function sktOnce(t: string): string {
  const k = t.trim();
  if (k && SKT_EXACT[k]) return t.replace(k, SKT_EXACT[k]);
  for (let i = 0; i < SKT_RE.length; i++) {
    const r = SKT_RE[i];
    t = typeof r[1] === 'string' ? t.replace(r[0], r[1]) : t.replace(r[0], r[1] as (...a: string[]) => string);
  }
  return skSym(t);
}
/** sktText(t): 터미널(.tft-page) 안의 글자 마디 하나. 원본은 바뀔 때마다 다시 돌므로 더 바뀌지 않을 때까지 적용한다 */
export function sktText(t: string): string {
  for (let i = 0; i < 4; i++) {
    const n = sktOnce(t);
    if (n === t) break;
    t = n;
  }
  return t;
}

