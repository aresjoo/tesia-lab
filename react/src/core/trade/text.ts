/** MKT_HOLD: 포지션을 들고 있을 때 판단 패널 문구를 보유 기준으로 */
const MKT_HOLD: [string, string][] = [['TETH가 진입 조건을 확인하고 있습니다', 'TETH가 청산 조건을 확인하고 있습니다'], ['아직 진입하지 않은 이유', '포지션 보유 이유'], ['다음 진입 조건', '청산 조건']];
const sub = (t: string, L: [string, string][]) => {
  let u = t;
  L.forEach((p) => {
    if (u.indexOf(p[0]) >= 0) u = u.split(p[0]).join(p[1]);
  });
  return u;
};
/** 판단 패널 안의 글자 마디 하나: sktText + tbText (+ mktHoldFix). hold 는 고른 전략이 실행 중이고 포지션을 들고 있을 때 */
export function brainText(t: string, hold = false): string {
  for (let i = 0; i < 4; i++) {
    let n = sub(sktText(t), TB_TXT);
    if (hold) n = sub(n, MKT_HOLD);
    if (n === t) break;
    t = n;
  }
  return t;
}
