/** skdText(t): 글자 마디 하나에 정규식 교체표와 심볼 이름(skSym)을 적용한다 */
export function skdText(t: string): string {
  for (let i = 0; i < SKD_RE.length; i++) t = t.replace(SKD_RE[i][0], SKD_RE[i][1] as never);
  return skSym(t);
}
/** 짧은 이름표(탭, 표 머리, 정보 행, 그래프 단추, 판단 기록 제목)용: 정확히 일치하면 바꾸고 아니면 skdText */
export function skdLabel(t: string): string {
  const k = t.trim();
  if (SKD_EXACT[k]) return t.replace(k, SKD_EXACT[k]);
  return skdText(t);
}
/** skdDedupe 의 규칙 설명 문장 가리기: 판단 기록(현재 포지션, 전략 개요 제외)에서 이 글자가 든 문장은 지운다 */
export const SKD_RULE = /레버리지는|반대 신호가 나오면 청산하고|되돌아오면 청산합니다|손실 방향으로 움직이면 청산합니다|한 종목을|양방향으로 거래합니다/;
/** 이름표 자리가 아닌 곳의 글자 마디 (원본 skdApply 의 조상 검사): 글자가 이름표와 똑같으면 그대로 두고, 아니면 skdText.
    원본은 화면이 바뀔 때마다 다시 훑으므로 더 바뀌지 않을 때까지 적용한다 */
export function skdBody(t: string): string {
  for (let n = 0; n < 4; n++) {
    if (SKD_EXACT[t.trim()]) return t;
    const v = skdText(t);
    if (v === t) return t;
    t = v;
  }
  return t;
}
