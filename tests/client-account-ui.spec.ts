import { expect, test, type Page } from '@playwright/test'

// A real Vite fixture resolves React without relying on optimizer internals.
async function fixture(page: Page) {
  await page.goto('/tests/fixtures/client-account-ui.html')
  await expect(page.getByRole('button', { name: 'signup', exact: true })).toBeVisible()
}

test('이메일 가입의 비밀번호·코드·성명·연령을 보존하고 자격증명을 저장하지 않는다', async ({ page }) => {
  const sent: string[] = []
  page.on('request', request => { if (request.method() !== 'GET') sent.push(request.url()) })
  await fixture(page)
  await page.getByRole('button', { name: 'signup', exact: true }).click()
  await page.getByRole('button', { name: '계속', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('올바른 이메일')
  await page.getByRole('textbox', { name: '이메일 주소' }).fill('research@example.test')
  await page.getByRole('button', { name: '계속', exact: true }).click()
  await expect(page.getByRole('heading', { name: '비밀번호 생성하기' })).toBeVisible()
  await page.getByLabel('비밀번호', { exact: true }).fill('sample-password-42!')
  await expect(page.locator('.rq.ok')).toHaveCount(3)
  await page.getByRole('button', { name: '비밀번호 표시' }).click()
  await expect(page.getByLabel('비밀번호', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: '계속', exact: true }).click()
  await expect(page.getByRole('heading', { name: '받은 편지함을 확인하세요' })).toBeVisible()
  await expect(page.getByRole('button', { name: '비밀번호로 계속하기' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /다시 보내기/ })).toBeDisabled()
  await page.getByRole('textbox', { name: '코드', exact: true }).fill('123456')
  await page.getByRole('button', { name: '계속', exact: true }).click()
  await page.getByRole('textbox', { name: '성명', exact: true }).fill('연구 사용자')
  await page.getByRole('textbox', { name: '연령', exact: true }).fill('121')
  await page.getByRole('button', { name: '시장에 입장하기' }).click()
  await expect(page.getByRole('alert')).toContainText('연령을 숫자로')
  await page.getByRole('textbox', { name: '연령', exact: true }).fill('28')
  await page.getByRole('button', { name: '시장에 입장하기' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('output')).toHaveText('연구 사용자 research@example.test')
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))).toEqual({ local: {}, session: {} })
  expect(sent).toEqual([])
})

