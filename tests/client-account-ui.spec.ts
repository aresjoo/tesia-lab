test('가입 미리보기 처리 중 취소하면 지연 완료가 계정 상태를 바꾸지 않는다', async ({ page }) => {
  await page.clock.install()
  await fixture(page)
  await page.getByRole('button', { name: 'signup', exact: true }).click()
  await page.locator('.au-btns button').first().click()
  await page.getByRole('textbox', { name: '연령', exact: true }).fill('28')
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
  await page.getByRole('button', { name: '시장에 입장하기' }).click()
  await expect(page.locator('.au-spin')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.clock.fastForward(2000)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('output')).toHaveText('')
  await expect(page.getByRole('button', { name: 'signup', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'signup', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '이메일 주소' })).toHaveValue('')
})
