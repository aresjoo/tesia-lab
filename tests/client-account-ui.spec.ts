test('설정 계층과 모바일 시트는 원본 메뉴와 언어/통화 동선을 유지한다', async ({ page }) => {
  await fixture(page)
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 800 })
    await page.getByRole('button', { name: 'settings', exact: true }).click()
    await page.getByRole('button', { name: '설정', exact: true }).click()
    await expect(page.getByRole('button', { name: /언어 및 통화/ })).toBeVisible()
    await expect(page.getByRole('button', { name: /테마/ })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const box = await page.locator('.gm-sub').boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width)
    await page.getByRole('button', { name: /언어 및 통화/ }).click()
    await expect(page.getByText('locale selected', { exact: true })).toBeVisible()
  }
})

