for(const language of ['ko','en','ja','zh-CN','zh-TW','es','fr'] as const)test(`${language} source buttons, confirmation and focus remain readable at 320px and 200%`,async({page})=>{
  await page.setViewportSize({width:320,height:900});await page.addInitScript(language=>localStorage.setItem('tethLang',language),language)
  await page.goto(`${path}#/settings/security`)
  await expect(page.getByRole('heading',{name:securityText(language,'devicesTitle'),exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:securityText(language,'exchangesTitle'),exact:true})).toBeVisible()
  const dialog=await open(page,'disconnectExchange')
  await expect(dialog.getByRole('heading')).toHaveText(securityText(language,'disconnectTitle').replace('{label}','Observed exchange'))
  await expect(dialog.getByRole('button',{name:settings.cancel[language],exact:true})).toBeFocused()
  await dialog.evaluate(node=>{for(const el of node.querySelectorAll<HTMLElement>('h2,p,button'))el.style.fontSize=`${parseFloat(getComputedStyle(el).fontSize)*2}px`})
  for(const el of await dialog.locator('h2,p,button').all())expect(await el.evaluate(node=>node.scrollWidth<=node.clientWidth+1)).toBe(true)
  await page.keyboard.press('Escape');await expect(page.locator(exchange+' button')).toBeFocused()
})
