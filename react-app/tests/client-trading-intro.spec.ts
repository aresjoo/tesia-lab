test('video ending restores the poster while the video fades and never loops',async({page})=>{
  await page.emulateMedia({reducedMotion:'no-preference'});await page.goto('/#/trade')
  const floor=page.locator('.txh-floor'),video=floor.locator('video')
  await expect(video).toHaveCount(1)
  await expect.poll(()=>video.evaluate((el:HTMLVideoElement)=>Number.isFinite(el.duration))).toBe(true)
  await expect(floor).toHaveClass(/playing/)
  expect(await video.evaluate((el:HTMLVideoElement)=>{el.currentTime=el.duration-.5;el.dispatchEvent(new Event('timeupdate'));return el.parentElement!.classList.contains('playing')})).toBe(false)
  await expect(floor).not.toHaveClass(/playing/)
  await expect(video).not.toHaveClass(/on/)
  await expect(floor.locator('img')).toHaveCSS('opacity','1')
  await expect(video).toHaveJSProperty('ended',true)
  await page.locator('.txh-safe').scrollIntoViewIfNeeded()
  await page.locator('.txh-hero').scrollIntoViewIfNeeded()
  await expect(video).toHaveJSProperty('paused',true)
})

