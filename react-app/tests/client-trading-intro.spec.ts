  await expect(root.locator('.txh-safe li')).toHaveCount(4)
  await expect(root.locator('.txh-note').first()).toHaveText('영원히 무료, 카드 등록 필요없음')
  await expect(root.locator('.txh-card').first()).toContainText('12,480')
  await expect(root.locator('.txh-example-note')).toContainText('실제 거래 기록이 아닙니다')
  await expect(page.locator('.client-site-footer')).toHaveCount(1)
  await expect(root.locator('video')).toHaveCount(0)
