test('배경 클릭은 닫고 내부에서 바깥으로 드래그하면 닫지 않으며 scroll lock을 복원한다', async ({ page }) => {
  await mount(page); await page.evaluate(() => document.body.style.overflow = 'clip')
  await open(page)
  const bounds = (await page.getByRole('dialog').boundingBox())!
  await page.mouse.move(bounds.x + 10, bounds.y + 10); await page.mouse.down(); await page.mouse.move(2, 2); await page.mouse.up()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.mouse.click(2, 2)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('clip')
  await expect(page.locator('.cmp-trigger')).toBeFocused()
})
