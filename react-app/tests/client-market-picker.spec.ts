async function mount(page: Page, fixture: PickerFixture = {}, language = 'ko') {
  await page.addInitScript(language => localStorage.setItem('tethLang', language), language)
  await page.goto('/')
  await page.evaluate(async fixture => { const path = '/tests/fixtures/market-picker-harness.tsx'; const { mountMarketPicker } = await import(/* @vite-ignore */ path); Reflect.set(window, 'pickerHarness', mountMarketPicker(fixture)) }, fixture)
  await expect(page.locator('#picker-test-root .ctm-header')).toBeVisible()
}
async function update(page: Page, fixture: PickerFixture) { await page.evaluate(fixture => Reflect.get(window, 'pickerHarness').update(fixture), fixture) }
const selections = (page: Page) => page.locator('.cmp-select')
const open = (page: Page) => page.locator('.cmp-trigger').click()

test('목록과 시장 헤더가 같은 로컬 종목 아이콘을 사용하고 실패·오래된 선택은 첫 글자로 대체한다', async ({ page }) => {
  await mount(page)
  const icon = page.locator('.ctm-symbol-icon')
  await expect(icon.locator('img')).toHaveAttribute('src', '/client-template-assets/btc.svg')
  await open(page)
  await page.getByRole('searchbox').fill('엔비디아')
  await selections(page).click()
  await expect(icon).toHaveText('N')
  await expect(icon.locator('img')).toHaveCount(0)
  await page.route('**/client-market-assets/NVDA.png', route => route.fulfill({ status: 404 }))
  await update(page, { selectedIcon: '/client-market-assets/NVDA.png' })
  await expect(icon.locator('img')).toBeHidden()
  await expect(icon).toHaveText('N')
  await update(page, { selectedIcon: '/client-template-assets/eth.svg' })
  await expect(icon.locator('img')).toBeVisible()
  await expect(icon.locator('img')).toHaveAttribute('src', '/client-template-assets/eth.svg')
  for (const fixture of [
    { selectedIcon: 'https://example.com/tracking.svg' },
    { selectedIcon: '/client-template-assets/eth.svg', selectedId: 'btc' },
    { selectedIcon: '/client-template-assets/eth.svg', duplicate: true },
  ]) {
    await update(page, fixture)
    await expect(icon.locator('img')).toHaveCount(0)
    await expect(icon).toHaveText('N')
  }
})

