async function mount(page: Page, fixture: InspectionFixture = {}) {
  await page.goto('/')
  await page.evaluate(async fixture => { const path = '/tests/fixtures/market-inspection-harness.tsx'; const { mountMarketInspection } = await import(/* @vite-ignore */ path); Reflect.set(window, 'inspectionHarness', mountMarketInspection(fixture)) }, fixture)
  await expect(page.locator('#inspection-test-root .client-account-terminal')).toBeVisible()
}
const requestCount = (page: Page) => page.evaluate(() => Reflect.get(window, 'inspectionHarness').requests().length)
const resolve = (page: Page, index: number, wrong = false) => page.evaluate(({ index, wrong }) => Reflect.get(window, 'inspectionHarness').resolve(index, wrong), { index, wrong })
const update = (page: Page, fixture: InspectionFixture) => page.evaluate(fixture => Reflect.get(window, 'inspectionHarness').update(fixture), fixture)
async function choose(page: Page, symbol: string) { await page.locator('.cmp-trigger').click(); await page.locator('.cmp-select').filter({ hasText: `${symbol}/USDT` }).click() }
const inspection = (page: Page) => page.locator('[data-market-inspection]')

test('선호는 owner별로 격리하고 미저장 상태를 유지하며 새 lifetime은 전략 추종으로 복원한다', () => {
  const values = new Map<string, string>(); let fail = false
  const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { if (fail) throw Error('blocked'); values.set(key, value) } }
  const store = createMarketSelectionStore('a', 'market', storage)
  store.favorite('BTC', true); store.select('ETH')
  expect(store.getSnapshot()).toMatchObject({ manualId: 'ETH', lastId: 'ETH', favorites: ['BTC'], storageError: false })
  const second = createMarketSelectionStore('a', 'market', storage)
  expect(second.getSnapshot()).toMatchObject({ manualId: null, lastId: 'ETH', favorites: ['BTC'] })
  expect(createMarketSelectionStore('b', 'market', storage).getSnapshot().favorites).toEqual([])
  second.favorite('SOL', true); store.favorite('ETH', true)
  expect(store.getSnapshot().favorites).toEqual(['BTC', 'SOL', 'ETH'])
  fail = true; expect(store.select('SOL')).toBe(false)
  expect(store.getSnapshot()).toMatchObject({ manualId: 'SOL', storageError: true })
  fail = false; expect(store.retry()).toBe(true)
  store.follow(); expect(store.getSnapshot()).toMatchObject({ manualId: null, lastId: 'SOL' })
})
