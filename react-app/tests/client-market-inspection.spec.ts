  const values = new Map<string, string>(); let fail = false
  const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { if (fail) throw Error('blocked'); values.set(key, value) } }
  const first = createMarketSelectionStore('a', 'market', storage)
  first.favorite('BTC', true); first.select('BTC')
