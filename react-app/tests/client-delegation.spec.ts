async function expectNoSensitiveStorage(page: Page) {
  const values = await page.evaluate(() => Object.values({ ...localStorage, ...sessionStorage }).join('\n'))
  expect(values).not.toMatch(/SAFE_FAKE|BAD_FAKE|42424242|1212345678|1234567890|테스트카드/)
  const records = await page.evaluate(() => Object.entries(sessionStorage).filter(([key]) => key.startsWith('teth:client-delegation:')).map(([, value]) => JSON.parse(value)))
  for (const record of records) expect(Object.keys(record).sort()).toEqual(['answers', 'attempt', 'chartInterval', 'expert', 'page', 'parameters', 'questionIndex', 'workStartedAt', 'workStep'])
}

