  await expect(page.locator('.tf-ez').first()).toContainText(`100번 중 ${Math.round(recommended.winRate)}번`)
  await page.getByRole('button', { name: '전문가 보기', exact: true }).click()
  await expect(page.locator('.tf-ez').first()).toContainText(`Profit Factor ${recommended.pf.toFixed(2)}`)
  await page.reload()
  await expect(page.getByRole('button', { name: '쉬운 말 보기', exact: true })).toBeVisible()
  await expect(page.locator('.tf-ez').first()).toContainText(`Profit Factor ${recommended.pf.toFixed(2)}`)
  await page.locator('.client-delegation .bk').click()
  const daily = Number(await page.locator('.tf-source-price').getAttribute('data-points'))
  await page.getByRole('button', { name: '1W', exact: true }).click()
  expect(Number(await page.locator('.tf-source-price').getAttribute('data-points'))).toBeLessThan(daily)
