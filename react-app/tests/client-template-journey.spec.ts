test('한글 조합 Enter는 보내지 않으며 전체화면에서도 선택과 초안을 유지한다', async ({ page }) => {
  await page.goto('/')
  await page.locator('.g-tpl[data-id="auto"]').click()
  const input = page.locator('#strategy-idea')
  await input.fill('첫째 조건\n둘째 조건')
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true })
  await expect(page.locator('.g-urow')).toHaveCount(0)
  await page.locator('.client-expand').click()
  await expect(page.getByRole('dialog', { name: '전체 화면 입력' })).toBeVisible()
  await expect(page.locator('.client-template-selection')).toContainText('AI가 대신 거래')
  await expect(input).toHaveValue('첫째 조건\n둘째 조건')
  await page.keyboard.press('Escape')
  await expect(input).toHaveValue('첫째 조건\n둘째 조건')
  await expect(input).toBeFocused()
})

test('반응형 하단 밴드에서 선택칩·입력·약관이 겹치지 않는다', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  for (const [width, height] of [[320,568],[390,844],[844,390],[1024,768],[1440,1000]]) {
    await page.setViewportSize({ width, height })
    await page.locator('.g-tpl[data-id="auto"]').click()
    await page.locator('#strategy-idea').fill('비트코인\n손절 기준도 정리해 주세요')
    const band = page.locator('.client-home-band')
    await expect(band).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    const parts = await band.evaluate(el => {
      const input = el.querySelector('textarea')!.getBoundingClientRect()
      const terms = el.querySelector('.client-home-terms')!.getBoundingClientRect()
      const chips = el.querySelector('.client-template-selection')!.getBoundingClientRect()
      return { separate: chips.bottom <= input.top + 1 && input.bottom <= terms.top + 1 }
    })
    expect(parts.separate).toBe(true)
    await page.screenshot({ path: info.outputPath(`gallery-band-${width}.png`) })
    await page.getByRole('button', { name: 'AI가 대신 거래 선택 해제' }).click()
  }
})
