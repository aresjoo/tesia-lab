import { expect, test } from '@playwright/test'

test('원본P0: 템플릿은 해석에만 쓰고 입력 원문을 말풍선·편집·새로고침에 보존한다', async ({ page }) => {
  test.setTimeout(30_000)
  await page.clock.install()
  await page.addInitScript(() => sessionStorage.setItem('teth-client-profile-preview', JSON.stringify({ name: '검색 검수자', email: 'intake@example.test' })))
  await page.goto('/')
  await page.locator('.g-tpl[data-id="auto"]').click()
  await page.locator('.g-tpl[data-id="btc"]').click()
  const raw = '하락 뒤 반등할 때 살래요\n조건은 같이 정해주세요'
  await page.locator('#strategy-idea').fill(raw)
  await page.locator('#strategy-idea').press('Enter')
  await expect(page.locator('.g-umsg')).toHaveText(raw)
  await page.clock.fastForward(15_000)
  const session = await page.evaluate(() => JSON.parse(sessionStorage.getItem('teth-client-experience')!).sessions[0])
  expect(session.pair).toBe('BTC/USDT')
  expect(session.turns[0].question).toBe(raw)
  expect(session.turns[0].requestText).toContain('BTC')
  await page.reload()
  await expect(page.locator('.g-umsg')).toHaveText(raw)
  await page.locator('.g-uacts button').first().click()
  await expect(page.locator('.g-composer textarea')).toHaveValue(raw)
  const historyButton = page.locator('.client-research-navigation nav button').first()
  if (!await historyButton.isVisible()) await page.locator((page.viewportSize()?.width ?? 0) <= 860 ? '.client-hamburger' : '.client-rail-logo-row button').click()
  await historyButton.click()
  const templateWords = session.turns[0].requestText.replace('. ' + raw, '')
  expect(raw).not.toContain(templateWords)
  await page.getByRole('searchbox', { name: '연구 기록 검색', exact: true }).fill(templateWords)
  // 원본 final gHistText는 해석 명령이 아닌 제목·가시 대화만 검색합니다.
  await expect(page.locator('.g-hist-row')).toHaveCount(0)
  await page.getByRole('searchbox', { name: '연구 기록 검색', exact: true }).fill('하락 반등')
  await expect(page.locator('.g-hist-row')).toHaveCount(1)
  await page.evaluate(() => {
    const value = JSON.parse(sessionStorage.getItem('teth-client-experience')!)
    value.sessions[0].turns[0].requestText = { damaged: true }
    sessionStorage.setItem('teth-client-experience', JSON.stringify(value))
  })
  await page.reload()
  await expect(page.locator('.g-umsg')).toHaveText(raw)
})

test('템플릿만 선택해 전송하고 같은 대화에서 이어 쓴다', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.locator('.g-tpl[data-id="auto"]').click()
  await page.locator('.g-tpl[data-id="btc"]').click()
  await expect(page.locator('#strategy-idea')).toHaveValue('')
  await expect(page.locator('.client-home-send')).toBeVisible()
  await page.locator('#strategy-idea').press('Enter')
  await expect(page.locator('.g-urow')).toHaveCount(1)
  await expect(page.locator('.g-urow')).toContainText('BTC')
  await expect(page.locator('.g-composer textarea')).toBeVisible()
  await expect(page.locator('.client-home-gallery')).toHaveCount(0)
  expect(errors).toEqual([])
})

