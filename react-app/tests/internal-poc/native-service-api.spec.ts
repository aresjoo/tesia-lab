test('v5 chart parses raw JSON separately; v6 report preserves native binding and MMR limitation', async ({ page }) => {
  const result = await page.evaluate(async data => {
    const modulePath = '/src/internal-poc/native-service-api.ts'
    const { createNativeServiceApi } = await import(/* @vite-ignore */ modulePath)
    const chart = data.sources[0].fixture as unknown as { binding: NativeChartManifest['binding']; sourcePolicy: NativeChartManifest['sourcePolicy']; meta: unknown; manifest: Omit<NativeChartManifest, 'binding' | 'sourcePolicy'>; window: Omit<NativeChartWindow, 'binding' | 'sourcePolicy'> }
    const report = data.sources[1].fixture as unknown as { response: { data: NativeReport } }
    const job = { ...(data.sources[3].fixture as unknown as { cases: { response: { data: NativeJob } }[] }).cases[0].response.data,
      state: 'COMPLETED', resultAvailable: true, nativeReportBinding: report.response.data.binding }
    const segment = report.response.data.nativeEnvelope.projection.segments[0]
    const binding = { ...chart.binding, backtestId: job.backtestId, splitGroupId: job.splitGroupId,
      strategyVersionId: job.strategyVersionId, semanticHash: job.semanticHash, resultContentHash: segment.resultContentHash }
    const segmentBounds = { fromInclusive: segment.evaluationStartInclusive, toExclusive: segment.evaluationEndExclusive }
    const manifest = { ...chart.manifest, binding, sourcePolicy: chart.sourcePolicy, segmentBounds,
      series: chart.manifest.series.map(series => ({ ...series, availableRange: segmentBounds })) }
    const requests: string[] = []
    const api = createNativeServiceApi({ request: async (request: { path: string }) => {
      requests.push(request.path)
      let body
      if (request.path.includes('native-report')) body = report.response
      else if (request.path.includes('chart-manifest')) body = { meta: chart.meta, data: manifest }
      else {
        const url = new URL(request.path, location.origin)
        const requestedRange = { fromInclusive: url.searchParams.get('fromInclusive'), toExclusive: url.searchParams.get('toExclusive') }
        body = { meta: chart.meta, data: { ...chart.window, binding, sourcePolicy: chart.sourcePolicy, resolution: url.searchParams.get('resolution'), aggregationPolicy: 'UTC_EPOCH_COMPLETE_OHLCV', requestedRange,
          bars: [], coverage: { status: 'UNAVAILABLE', coveredRanges: [], missingRanges: [requestedRange] } } }
      }
      return { status: 200, headers: { 'cache-control': 'no-store', etag: '"synthetic_etag_1234567890"' }, body: JSON.stringify(body) }
    } })
    const actualReport = await api.report(job)
    const actualChart = await api.chart(job, actualReport, 'IS')
    manifest.series = manifest.series.map(series => ({ ...series, supportedResolutions: ['1m', '15m', '1h'],
      availableRange: { ...segmentBounds, fromInclusive: '2024-01-01T00:15:00Z' } }))
    const hourlyChart = await api.chart(job, actualReport, 'IS')
    const hourBuckets = Math.floor((Date.parse(hourlyChart.window.requestedRange.toExclusive) - 1) / 3600000)
      - Math.floor(Date.parse(hourlyChart.window.requestedRange.fromInclusive) / 3600000) + 1
    manifest.segmentBounds = { ...segmentBounds, fromInclusive: '2024-01-01T00:01:00Z' }
    let wrongBoundsRejected = false
    try { await api.chart(job, actualReport, 'IS') } catch { wrongBoundsRejected = true }
    let rejected = false
    try { await api.report({ ...job, nativeReportBinding: { ...job.nativeReportBinding, terminalSealContentHash: 'a'.repeat(64) } }) } catch { rejected = true }
    return { requests, source: actualReport.binding.evidenceClass, limitation: actualReport.binding.liquidationCheckStatus,
      chartStatus: actualChart.window.coverage.status, bars: actualChart.view.bars.length, rejected, hourBuckets, wrongBoundsRejected }
  }, fixtures)
  expect(result.source).toBe('SYNTHETIC_CONTRACT_FIXTURE')
  expect(result.limitation).toBe('UNAVAILABLE')
  expect(result.chartStatus).toBe('UNAVAILABLE')
  expect(result.bars).toBe(0)
  expect(result.rejected).toBe(true)
  expect(result.hourBuckets).toBe(1000)
  expect(result.wrongBoundsRejected).toBe(true)
  expect(result.requests.some(path => path.includes('/api/v5/') && path.includes('chart-window'))).toBe(true)
})
