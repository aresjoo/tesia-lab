test('result pagination keeps confirmed page after failure and allows the same cursor retry', async ({ page }) => {
  await page.evaluate(async data => {
    const refreshPath = '/@react-refresh'
    const runtime = (await import(/* @vite-ignore */ refreshPath)).default
    runtime.injectIntoGlobalHook(window)
    Object.assign(window, { $RefreshReg$: () => {}, $RefreshSig$: () => (type: unknown) => type, __vite_plugin_react_preamble_installed__: true })
    const reactPath = '/@id/react', domPath = '/@id/react-dom/client', panelPath = '/src/internal-poc/NativeServiceResult.tsx'
    const react = await import(/* @vite-ignore */ reactPath), dom = await import(/* @vite-ignore */ domPath)
    const { NativeServiceResult } = await import(/* @vite-ignore */ panelPath)
    const report = (data.sources[1].fixture as unknown as { response: { data: NativeReport } }).response.data
    let attempts = 0
    const api = { report: async () => report, trades: async (_report: unknown, _segment: unknown, cursor?: string) => {
      if (cursor !== undefined) {
        if (cursor !== 'synthetic_ui_cursor') throw new Error('WRONG_CURSOR')
        if (++attempts === 1) throw new Error('SYNTHETIC_RESPONSE_LOSS')
      }
      return { trades: [], nextCursor: cursor === undefined ? 'synthetic_ui_cursor' : null }
    }, chart: async () => { throw new Error('SYNTHETIC_CHART_UNAVAILABLE') } }
    const root = document.createElement('div'); document.body.append(root)
    // Isolated display fixture, not a substitute for generated SDK/API verification.
    ;(dom.createRoot ?? dom.default.createRoot)(root).render((react.createElement ?? react.default.createElement)(NativeServiceResult, { api, job: { backtestId: report.binding.backtestId } }))
  }, fixtures)
  const result = page.getByRole('region', { name: '백테스트 결과' })
  await expect(result).toContainText('1페이지 · 현재 0건')
  await result.getByRole('button', { name: '다음 거래 페이지' }).click()
  await expect(result).toContainText('마지막으로 확인한 페이지를 유지합니다.')
  await expect(result).toContainText('1페이지 · 현재 0건')
  await result.getByRole('button', { name: '다음 거래 페이지' }).click()
  await expect(result).toContainText('2페이지 · 현재 0건')
  await expect(result).not.toContainText('마지막으로 확인한 페이지를 유지합니다.')
  await expect(result.getByRole('button', { name: '다음 거래 페이지' })).toHaveCount(0)
})

test('vendored native SDK retains published generated bytes', () => {
  for (const version of ['0.5', '0.6', '0.7', '0.8']) {
    const root = new URL(`../../src/internal-poc/contracts/generated/api-v${version}/`, import.meta.url)
    const manifest = JSON.parse(readFileSync(new URL('generation-manifest.json', root), 'utf8'))
    for (const file of ['client.ts', 'types.ts', 'validator.ts', 'index.ts', 'operation-manifest.json']) {
      expect(createHash('sha256').update(readFileSync(new URL(file, root))).digest('hex')).toBe(manifest.generatedSha256[file])
    }
  }
})

