const fs=require('fs'); const f=__dirname+'/sk-term.js'; let s=fs.readFileSync(f,'utf8');
const rep=(a,b)=>{ const n=s.split(a).length-1; if(n!==1) throw new Error('count '+n+' '+a.slice(0,60)); s=s.replace(a,b); };
rep(`'전략을 선택하면 여기에 표시됩니다':'전략을 고르면 여기에 표시합니다'`, `'전략을 선택하면 여기에 표시됩니다':'선택한 전략을 표시합니다.'`);
rep(`'채팅에서 전략을 만들고 검증을 통과하면 여기서 실행됩니다.':'채팅에서 전략을 만들고 검증을 마치면 여기서 실행합니다.'`, `'채팅에서 전략을 만들고 검증을 통과하면 여기서 실행됩니다.':'채팅에서 만든 전략을 검증한 뒤 실행할 수 있습니다.'`);
rep(`'데모 체험, 시뮬레이션 데이터입니다':'미리보기 화면입니다. 예시 전략으로 보여 드립니다.',`, `'데모 체험, 시뮬레이션 데이터입니다':'예시 전략의 운용 화면을 미리 봅니다.','내 화면으로':'내 터미널','TETH가 보고 있습니다':'TETH가 진입 조건을 확인하고 있습니다',`);
rep(`'검증 구간 재생, 일봉':'검증 구간 기록, 일봉'`, `'검증 구간 재생, 일봉':'일봉 기준 검증 기록'`);
rep(`  [/^이전 판단 더 보기 \\((\\d+)\\)$/,'이전 판단 더 보기, $1건']`,
`  [/^이전 판단 더 보기 \\((\\d+)\\)$/,'이전 판단 더 보기, $1건'],
  [/^시장가 (매도|매수) 전량, /,'전량 시장가 $1, '],
  [/^(\\d{4})\\.(\\d{2})\\.(\\d{2})$/,function(_,y,m,d){ return y+'. '+(+m)+'. '+(+d)+'.'; }],
  [/^(\\d{4})\\.(\\d{2})\\.(\\d{2}) ~ (\\d{4})\\.(\\d{2})\\.(\\d{2})$/,function(_,a,b,c,d,e,g){ return a+'. '+(+b)+'. '+(+c)+'. ~ '+d+'. '+(+e)+'. '+(+g)+'.'; }]`);
fs.writeFileSync(f,s); console.log('ok');
